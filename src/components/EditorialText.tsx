export function EditorialText({ text, language }: {text:string; language:Locale}) {
  if(language !== "fa") return <>{text}</>;
  const phrases = selections.get(text);
  if(!phrases?.length) return <>{text}</>;
  const ranges = phrases.map(phrase=>({start:text.indexOf(phrase),end:text.indexOf(phrase)+phrase.length})).filter(r=>r.start>=0).sort((a,b)=>a.start-b.start);
  let position=0;
  const nodes=ranges.flatMap(r=>{
    if(r.start<position)return [];
    const prefix=text.slice(position,r.start);
    position=r.end;
    return [<Fragment key={"t"+r.start}>{prefix}</Fragment>,<strong className="editorial-emphasis" key={"b"+r.start}>{text.slice(r.start,r.end)}</strong>];
  });
  return <>{nodes}{text.slice(position)}</>;
}
